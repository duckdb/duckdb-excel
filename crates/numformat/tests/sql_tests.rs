#[test]
fn test_excel_numformat_currency_text() {
    check(1234.567, "$", "$");
    check(1234.567, "€", "€");
    check(1234.567, "\"$\"", "$");
    check(1234.567, "$-", "$-");
    // digit placeholders still make it a currency format
    check(1234.567, "$#", "$1235");
    check(1234.567, "$#,##0.00", "$1,234.57");
    check(-1234.567, "$#,##0.00", "-$1,234.57");
    check(1234.567, "$0,00", "$1,235");
}

#[test]
fn test_excel_numformat_long_format() {
    // inserting grouping separators used to write past the end of the symbol array
    check(1234567.897, &format!("{}{}", "$#,##0", "9".repeat(70)), "");
    // 70 extra digits plus their separators fit exactly within the symbol limit
    check(
        1234567.897,
        &format!("{}{}", "#,##0", "0".repeat(70)),
        "00,000,000,000,000,000,000,000,000,000,000,000,000,000,000,000,000,000,000,000,000,001,234,568",
    );
    // one more digit exceeds the limit
    check(1234567.897, &format!("{}{}", "#,##0", "0".repeat(71)), "");
    check(1234567.897, &format!("{}{}", "#,##0", "0".repeat(500)), "");
}
