#[test]
fn test_excel_numformat_separators() {
    check(1234567.897, "#,###", "1,234,568");
    check(1234567.897, "0,000.00", "1,234,567.90");
    check(1234567.897, "#,", "1235");
    check(1234567.897, "#,000.0", "1,234,567.9");
    check(1234567.897, "0.0,,", "1.2");
    check(1234567.897, "#,", "1235");
    check(1234567.897, "$#,###.00", "$1,234,567.90");
    check(1234567.897, "0,0,0,0", "1,234,568");
}

#[test]
fn test_excel_numformat_number_currency_accounting() {
    check(1234567.897, "$#,##0", "$1,234,568");
    check(1234567.897, "$,##0.00_", "$,1234567.90 ");
    check(1234567.897, "$#,##0.00", "$1,234,567.90");
    check(1234567.897, "$*#,##0", "$,1234568");
    check(1234567.897, "$*#,##0.00", "$,1234567.90");
    check(1234567.897, "$ 0.##", "$ 1234567.9");
}

#[test]
fn test_excel_numformat_others() {
    check(1234567.897, "####", "1234568");
    check(1234567.897, "##.###", "1234567.897");
    check(1234567.897, "0.00", "1234567.90");
    check(1234567.897, "#.", "1234568.");
    check(1234567.897, "#", "1234568");
    check(1234567.897, "#;#", "1234568");
    check(1234567.897, "#.", "1234568.");
    check(1234567.897, ".##000#", "1234567.89700");
    check(1234567.897, "#.#", "1234567.9");
    check(1234567.897, "##.00##", "1234567.897");
    check(1234567.897, "#_x#", "123456 8");
    check(1234567.897, "[>1]##", "1234568");
    check(1234567.897, "[<=0]##;[>0]##.0", "1234567.9");
    check(1234567.897, "[<>3.90e2]##", "1234568");
    check(1234567.897, "0", "1234568");
    check(
        123456789123.0,
        "[<=9999999]##-####;[>9999999](###) ###-####",
        "(12345) 678-9123",
    );
    check(
        1234567.0,
        "[<=9999999]##-####;[>9999999](###) ###-####",
        "123-4567",
    );
    check(1234567.897, "$$$$$$$0", "$$$$$$$1234568");
    check(
        1234567.897,
        "_ $* #,##0_ ;_ $* -#,##0_ ;_ $*  - _ ;_ @_ ",
        " $1,234,568 ",
    );
    check(
        -1234567.897,
        "_ $* #,##0_ ;_ $* -#,##0_ ;_ $*  - _ ;_ @_ ",
        " $-1,234,568 ",
    );
    check(0.0, "_ $* #,##0_ ;_ $* -#,##0_ ;_ $*  - _ ;_ @_ ", " $ -  ");
    check(
        1234567.897,
        "_ $* #,##0.00_ ;_ $* -#,##0.00_ ;_ $*  - ??_ ;_ @_ ",
        " $1,234,567.90 ",
    );
    check(
        -1234567.897,
        "_ $* #,##0.00_ ;_ $* -#,##0.00_ ;_ $*  - ??_ ;_ @_ ",
        " $-1,234,567.90 ",
    );
    check(
        0.0,
        "_ $* #,##0.00_ ;_ $* -#,##0.00_ ;_ $*  - ??_ ;_ @_ ",
        " $ -    ",
    );
    check(1.0, "3.5", "3.5");
}

