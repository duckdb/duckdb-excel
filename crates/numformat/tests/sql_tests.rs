//! The expectations of the SQL tests `test/sql/excel/test_excel_numformat*.test`.

use excel_numformat::format_number;

#[track_caller]
fn check(value: f64, format: &str, expected: &str) {
    assert_eq!(
        format_number(format, value),
        expected,
        "text({value}, {format:?})"
    );
}

#[test]
fn test_excel_numformat_hours_minutes_seconds() {
    check(1234567.897, "h", "21");
    check(1234567.897, "hh", "21");
    check(1234567.897, "s", "41");
    check(1234567.897, "ss", "41");
    check(12345.678, "[h]", "296296");
    check(12345.678, "[m]", "17777776");
    check(12345.678, "[s]", "1066666579");
    check(12345.678, "[hh]", "296296");
    check(12345.678, "[mm]", "17777776");
    check(12345.678, "[ss]", "1066666579");
}

#[test]
fn test_excel_numformat_composed_time_formats() {
    check(1234567.897, "h AM/PM", "9 PM");
    check(1234567.897, "h:mm AM/PM", "9:31 PM");
    check(1234567.897, "h:mm:ss A/P", "9:31:41 p");
    check(1234567.897, "h:mm:ss.00", "21:31:40.80");
    check(12345.678, "[h]:mm", "296296:16");
    check(1234567.897, "h m", "21 31");
    check(1234567.897, "m", "2");
    check(1234567.897, "mm", "02");
    check(1234567.897, "h m", "21 31");
    check(1234567.897, "m s", "31 41");
    check(12345.678, "[mm]:ss", "17777776:19");
    check(12345.678, "[m]:ss", "17777776:19");
    check(12345.678, "[s].00", "1066666579.20");
    check(12345.678, "[ss].00", "1066666579.20");
}

#[test]
fn test_excel_numformat_date_time() {
    check(1234567.897, "dd", "15");
    check(1234567.897, "d", "15");
    check(1234567.897, "dd.mm", "15.02");
    check(1234567.897, "dd/mm", "15/02");
    check(1234567.897, "mm/dd/yyyy", "02/15/5280");
    check(1234567.897, "m/d/yyyy h:mm AM/PM", "2/15/5280 9:31 PM");
    check(
        1234567.897,
        "dddd, dd of MMMM of YYYY",
        "Thursday, 15 of February of 5280",
    );
    check(1234567.897, "aaa", "Thu");
    check(1234567.897, "AaaA", "Thursday");
    check(1234567.897, "dddD", "Thursday");
    check(1234567.897, "dDd, dd of MMMM", "Thu, 15 of February");
    check(1234567.897, "mmmm", "February");
    check(1234567.897, "mmM", "Feb");
}

